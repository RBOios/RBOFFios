/* ---- 0x44e030  sort_native(base, out, pcount, pspecial)  cdecl:  see the file comment ---- */
static void flags_cmp(int32_t a,int32_t b){      /* flags of  cmp a,b  (a-b) */
    uint32_t r=(uint32_t)a-(uint32_t)b;
    cpu.CF=((uint32_t)a<(uint32_t)b); cpu.ZF=(r==0); cpu.SF=(r>>31)&1;
    cpu.OF=((((uint32_t)a^(uint32_t)b)&((uint32_t)a^r))>>31)&1; cpu.PF=!__builtin_parity(r&0xff); cpu.AF=(((uint32_t)a^(uint32_t)b^r)>>4)&1;
}
/* returns 0 when the arguments are not what the fast path assumes (the original code then runs) */
static int sort_native(uint32_t sp){
    const uint32_t T0=0x024b41c8u, T1=0x024b41ccu, T2=0x024b41d0u;
    uint32_t a1=rd32(sp+4), out=rd32(sp+8), pcnt=rd32(sp+12), pspc=rd32(sp+16);
    const uint64_t SRC=0x5cull*40+0x40, OUTN=12ull*40+16;
    if(!range_ok(a1,SRC)||!range_ok(out,OUTN)||!range_ok(pcnt,4)||!range_ok(pspc,4)||!range_ok(sp-16,0x24)) return 0;
    #define OV(p,n,q,m) ((uint64_t)(p)<(uint64_t)(q)+(m) && (uint64_t)(q)<(uint64_t)(p)+(n))
    if(pcnt==pspc || OV(pcnt,4,a1,SRC)||OV(pspc,4,a1,SRC)||OV(pcnt,4,out,OUTN)||OV(pspc,4,out,OUTN)||OV(out,OUTN,a1,SRC)) return 0;
    if(OV(pcnt,4,sp-16,0x24)||OV(pspc,4,sp-16,0x24)||OV(out,OUTN,sp-16,0x24)||OV(a1,SRC,sp-16,0x24)) return 0;
    if(OV(T0,12,a1,SRC)||OV(T0,12,out,OUTN)||OV(T0,12,pcnt,4)||OV(T0,12,pspc,4)||OV(T0,12,sp-16,0x24)||!range_ok(T0,12)) return 0;
    #undef OV
    wr32(sp-4,cpu.r[EBX]); wr32(sp-8,cpu.r[EBP]); wr32(sp-12,cpu.r[ESI]); wr32(sp-16,cpu.r[EDI]);      /* push ebx,ebp,esi,edi */
    wr32(pspc,0); wr32(pcnt,0);
    uint32_t ecx=a1+0x38;
    for(uint32_t esi=0;esi<0x28;esi++,ecx+=0x5c){
        if(rd32(ecx-4)==0) continue;
        if(rd32(ecx)==0) continue;
        if(rd32(ecx-0x10)==0xffffu){ wr32(pspc,ecx-0x38); continue; }
        uint32_t n=rd32(pcnt);          wr32(out+n*12u,esi);
        n=rd32(pcnt);                   wr32(out+n*12u+4,ecx-0x38);
        uint32_t k=(uint32_t)gmem[ecx+4];
        n=rd32(pcnt);                   wr32(out+n*12u+8,(k<<8)+esi);
        n=rd32(pcnt);                   wr32(pcnt,n+1);
    }
    uint32_t n=rd32(pcnt); int32_t edx=(int32_t)n-1;
    cpu.r[EAX]=pcnt;
    if(edx<=0){                                              /* test edx,edx ; jle end */
        cpu.r[ECX]=n; cpu.r[EDX]=(uint32_t)edx;
        cpu.ZF=(edx==0); cpu.SF=(edx<0); cpu.PF=!__builtin_parity((uint32_t)edx&0xff); cpu.CF=0; cpu.OF=0; cpu.AF=0;
    } else {
        uint32_t esi=1, edi=out; wr32(sp+0x10,esi);
        int32_t ebx;
        for(;;){
            ecx=n; edx=(int32_t)esi;                         /* cmp esi,ecx ; mov edx,esi ; jge outer_next */
            if(!((int32_t)esi>=(int32_t)ecx)){
                ecx=edi+0xc;
                for(;;){
                    int32_t kb=(int32_t)rd32(edi+8), kc=(int32_t)rd32(ecx+8);
                    if(kb>kc){
                        wr32(T0,rd32(edi)); wr32(T1,rd32(edi+4)); wr32(T2,rd32(edi+8));
                        wr32(edi,rd32(ecx)); wr32(edi+4,rd32(ecx+4)); wr32(edi+8,rd32(ecx+8));
                        wr32(ecx,rd32(T0)); wr32(ecx+4,rd32(T1)); wr32(ecx+8,rd32(T2));
                        esi=rd32(sp+0x10);
                    }
                    ebx=(int32_t)rd32(pcnt); edx++; ecx+=0xc;
                    if(!(edx<ebx)) break;
                }
            }
            ecx=rd32(pcnt); esi++; edi+=0xc; wr32(sp+0x10,esi);
            edx=(int32_t)esi-1; ebx=(int32_t)ecx-1;
            if(!(edx<ebx)) break;
            n=ecx;
        }
        cpu.r[ECX]=ecx; cpu.r[EDX]=(uint32_t)edx; flags_cmp(edx,ebx);
    }
    return 1;
}
