#!/usr/bin/env python3
"""Translate the straight-line x87 matrix-multiply functions of RBO_Ex3.exe into C that performs the same double-precision
operations in the same order, with loads/stores interleaved exactly like the original (so aliased dst/A/B behave identically)."""
import sys
code=open(sys.argv[1] if len(sys.argv)>1 else 'code_412000.bin','rb').read(); BASE=0x412000   # guest memory 0x412000..0x414000 (dump from the exe or a save state)
FUNCS=[('mm4',0x412b40,0x412d53),('mm3',0x412f00,0x412fe6)]
REG={0:'pA',1:'pB',2:'pD'}            # eax=[esp+8]  ecx=[esp+0xc]  edx=[esp+4]
def translate(name,lo,hi):
    b=code[lo-BASE:hi-BASE+1]; i=0; out=[]; depth=0; maxd=0
    pro=[b[0:4],b[4:8],b[8:12]]
    assert pro[0]==bytes.fromhex('8b442408') and pro[1]==bytes.fromhex('8b4c240c') and pro[2]==bytes.fromhex('8b542404'),name
    i=12
    def mem(modrm,i):
        mod,rm=modrm>>6,modrm&7
        assert mod in (0,1) and rm in (0,1,2),hex(modrm)
        disp=0
        if mod==1: disp=b[i]; i+=1; assert disp<0x80
        return '%s+0x%x'%(REG[rm],disp),i
    def push(expr):
        nonlocal depth,maxd
        out.append('s%d=%s;'%(depth,expr)); depth+=1; maxd=max(maxd,depth)
    while i<len(b):
        op=b[i]; i+=1
        if op==0xC3: assert i==len(b); out.append('/* ret */'); break
        if op==0xD9:
            m=b[i]; i+=1
            if m==0xC9: out.append('{ double t=s%d; s%d=s%d; s%d=t; } /* fxch st1 */'%(depth-1,depth-1,depth-2,depth-2)); continue
            r=(m>>3)&7; a,i=mem(m,i)
            if r==0: push('LDF(%s)'%a)
            elif r==3: out.append('STF(%s,s%d);'%(a,depth-1)); depth-=1
            else: raise SystemExit('unhandled d9 /%d'%r)
        elif op==0xD8:
            m=b[i]; i+=1; r=(m>>3)&7; assert m<0xC0
            a,i=mem(m,i); sym={0:'+',1:'*',4:'-'}
            if r in sym: out.append('s%d=s%d%s LDF(%s);'%(depth-1,depth-1,sym[r],a))
            else: raise SystemExit('unhandled d8 /%d'%r)
        elif op==0xDE:
            m=b[i]; i+=1
            if m==0xC1: out.append('s%d=s%d+s%d;'%(depth-2,depth-2,depth-1)); depth-=1     # faddp st1,st
            else: raise SystemExit('unhandled de %02x'%m)
        else: raise SystemExit('unhandled opcode %02x at %x'%(op,lo+i-1))
    assert depth==0,(name,depth)
    body='\n    '.join(out)
    decl='double '+','.join('s%d'%k for k in range(maxd))+';'
    c='static void %s_native(uint32_t pA,uint32_t pB,uint32_t pD){\n    %s\n    %s\n}\n'%(name,decl,body)
    return c,b
print('/* GENERATED by gen_mm.py from the x87 code of RBO_Ex3.exe (KR build) - do not edit by hand */')
print('#pragma STDC FP_CONTRACT OFF                     /* clang: no fused multiply-add, results must match the interpreter bit for bit */')
print('#if defined(__GNUC__) && !defined(__clang__)\n#pragma GCC optimize("fp-contract=off")\n#endif')
print('static inline double LDF(uint32_t a){ float f; memcpy(&f,gmem+a,4); return (double)f; }')
print('static inline void STF(uint32_t a,double v){ float f=(float)v; memcpy(gmem+a,&f,4); }')
for n,lo,hi in FUNCS:
    c,b=translate(n,lo,hi)
    print('static const uint8_t %s_body[%d]={%s};'%(n,len(b),','.join('0x%02x'%x for x in b)))
    print(c)
